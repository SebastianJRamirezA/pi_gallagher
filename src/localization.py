def get_language() -> str:
    return _language


def set_language(language: str) -> None:
    global _language
    if language not in ("en", "es"):
        raise ValueError(f"Unsupported language: {language}")
    _language = language


def toggle_language() -> str:
    set_language("es" if get_language() == "en" else "en")
    return get_language()


def tr(text: str) -> str:
    if get_language() == "es":
        return text
    translated = _ENGLISH.get(text)
    if translated is not None:
        return translated
    if "\n" in text:
        return "\n".join(_ENGLISH.get(line, line) for line in text.split("\n"))
    return text


def localize(value: Any) -> Any:
    """Translate display data recursively while preserving its data structure."""
    if isinstance(value, str):
        return tr(value)
    if isinstance(value, list):
        return [localize(item) for item in value]
    if isinstance(value, tuple):
        return tuple(localize(item) for item in value)
    if isinstance(value, dict):
        return {key: localize(item) for key, item in value.items()}
    return value
